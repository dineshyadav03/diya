"""A knowledge base from your own notes: one Markdown page per recurring name, made of your own sentences (docs/KNOWLEDGE_DESIGN.md, unit K1 step 1).

    python diya_knowledge.py build [--notes DIR] [--out DIR] [--dry-run]    read the notes, write the pages
    python diya_knowledge.py list                                           the pages that exist, and the names hidden
    python diya_knowledge.py hide NAME                                      remove a name's page and never make it again
    python diya_knowledge.py unhide NAME                                    make it again from the next build

`build` only READS the notes folder (DIYA_NOTES_DIR) and writes the knowledge folder (DIYA_KNOWLEDGE_DIR, `knowledge/` by default). No model is used and no network: a page holds sentences copied word for
word from your notes, grouped under the name they mention, so nothing can be invented. A name gets a page when you marked it (`[[Name]]` or `@Name`), when Diya already knows the person (the Memory
page), or when it is a capitalised name that recurs in two or more different notes. A file in the knowledge folder that does not start with Diya's marker line is yours and is never changed or deleted.

Text from a note is only ever copied into a page as text: it is not sent to a model, nothing is run or fetched because of it, and a name made of anything but letters, digits, spaces and a few marks gets
no page, so a note cannot make Diya write outside its folder.
"""
from __future__ import annotations

import argparse
import os
import re
import sqlite3
import sys
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from pathlib import Path

import diya_config
from diya_memory import printable

MARKER_PREFIX = "<!-- diya-knowledge:"
MARKER = MARKER_PREFIX + " generated by Diya from your notes; edits are overwritten by the next build. -->"
SUFFIXES = (".txt", ".md", ".markdown")
MAX_FILE_BYTES = 200_000
MAX_FILES = 5000
MAX_DEPTH = 4  # sub-folders below the notes folder
UNIT_CHARS = 300
MAX_UNITS_PER_NOTE = 2000
MAX_TOTAL_BYTES = 50_000_000  # of notes read in one build
MIN_NOTES = 2  # a capitalised name must appear in this many different notes to get a page
MAX_BULLETS = 40
MAX_PAGES = 300
MAX_WITH = 8
NAME_CHARS = 60
HIDDEN_FILE = "hidden.txt"
INDEX_STEM = "index"
_RESERVED = frozenset({INDEX_STEM, "con", "prn", "aux", "nul"} | {f"com{n}" for n in range(1, 10)} | {f"lpt{n}" for n in range(1, 10)})
EXIT_OK, EXIT_FAILED, EXIT_USAGE = 0, 1, 2

# Words that begin a sentence or sit in a title without being a name, kept lowercase (compared without apostrophe style).
STOP = frozenset(
    """i i'm i'll i've i'd we we're you he she it they the a an this that these those my our your his her their its and or but so if when then there here what who how why also today tomorrow yesterday
    tonight now ok okay yes no note notes todo to of in on at for with from by as is are was were be do did don't can will should would could not just maybe please thanks hello hi hey dear re fwd
    monday tuesday wednesday thursday friday saturday sunday january february march april may june july august september october november december""".split()
)

_BULLET = re.compile(r"^\s*(?:[-*+]\s+(?:\[[ xX]\]\s+)?|\d+[.)]\s+|#{1,6}\s+|>\s*)+")
_TOKEN = re.compile(r"[^\W\d_][\w'’\-]*")
_WIKI = re.compile(r"\[\[([^\]\|#\n]{1,120})(?:[#|][^\]\n]*)?\]\]")
_AT = re.compile(r"(?<![\w@])@([^\W\d_][\w'\-]{1,40})")
_NAME_OK = re.compile(r"^[^\W_][\w \-'’.&]*$")
_TITLES = frozenset("dr mr mrs ms miss prof sir madam".split())
_ABBREV = frozenset("dr mr mrs ms prof st jr sr vs e.g i.e etc no approx".split())


class KnowledgeError(Exception):
    """Something the person has to fix (a folder that is missing, two folders that overlap); said in plain words."""


@dataclass
class Note:
    path: str  # relative to the notes folder, with forward slashes
    text: str
    mtime: int


@dataclass
class Report:
    notes: int = 0
    skipped: list = field(default_factory=list)
    pages: int = 0
    written: list = field(default_factory=list)
    unchanged: list = field(default_factory=list)
    removed: list = field(default_factory=list)
    collisions: list = field(default_factory=list)
    refused_names: int = 0
    over_page_limit: int = 0


# ---- reading -----------------------------------------------------------------------------------------------------


def _inside(root, path):
    try:
        return os.path.commonpath([root, path]) == root
    except ValueError:  # another drive
        return False


def read_notes(root, skip=()):
    """The notes under `root` as (notes, skipped): `.txt`, `.md` and `.markdown` files, sub-folders too up to MAX_DEPTH, never a hidden folder or anything that is not really inside `root`, never a
    file over MAX_FILE_BYTES, never a page Diya itself made. `skipped` says why for each file left out that a person might expect to see."""
    root_real = os.path.realpath(root)
    if not os.path.isdir(root_real):
        raise KnowledgeError(f"the notes folder {root!r} does not exist (DIYA_NOTES_DIR)")
    skip_real = {os.path.realpath(p) for p in skip}
    notes, skipped, total = [], [], 0
    for dirpath, dirnames, filenames in os.walk(root_real, followlinks=False):
        depth = 0 if dirpath == root_real else dirpath[len(root_real):].count(os.sep)
        dirnames[:] = sorted(
            d for d in dirnames
            if not d.startswith(".") and depth < MAX_DEPTH and os.path.realpath(os.path.join(dirpath, d)) not in skip_real and _inside(root_real, os.path.realpath(os.path.join(dirpath, d)))
        )
        for name in sorted(filenames):
            if not name.lower().endswith(SUFFIXES):
                continue
            full = os.path.join(dirpath, name)
            rel = os.path.relpath(full, root_real).replace(os.sep, "/")
            if not _inside(root_real, os.path.realpath(full)):
                skipped.append(f"{rel}: it leads outside the notes folder")
                continue
            try:
                info = os.stat(full)
                if info.st_size > MAX_FILE_BYTES:
                    skipped.append(f"{rel}: over {MAX_FILE_BYTES // 1000} KB")
                    continue
                with open(full, "rb") as handle:
                    text = handle.read().decode("utf-8-sig", errors="replace")
            except OSError as exc:
                skipped.append(f"{rel}: {exc.strerror or 'could not be read'}")
                continue
            if text.startswith(MARKER_PREFIX):
                continue  # one of Diya's own pages: never read back as a note
            total += len(text)
            if len(notes) >= MAX_FILES or total > MAX_TOTAL_BYTES:
                skipped.append(f"more than {MAX_FILES} notes or {MAX_TOTAL_BYTES // 1_000_000} MB of them: the rest were not read")
                return sorted(notes, key=lambda n: n.path), skipped
            notes.append(Note(rel, text, info.st_mtime_ns))
    return sorted(notes, key=lambda n: n.path), skipped


def _lines(text):
    """The lines of a note worth reading: without a leading front-matter block and without fenced code."""
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    if lines and lines[0].strip() == "---":
        for index in range(1, min(len(lines), 60)):
            if lines[index].strip() == "---":
                lines = lines[index + 1:]
                break
    out, fenced = [], False
    for line in lines:
        if line.lstrip().startswith(("```", "~~~")):
            fenced = not fenced
            continue
        if not fenced:
            out.append(line)
    return out


def _cut(sentence):
    if len(sentence) <= UNIT_CHARS:
        return sentence
    head = sentence[:UNIT_CHARS]
    return (head.rsplit(" ", 1)[0] if " " in head else head) + "..."


def units_of(text):
    """A note as sentences: each line (a bullet or a heading is one too) cut after . ! ? when a capital follows. Each is a run of the note's own words, cut to UNIT_CHARS."""
    units = []
    for line in _lines(text):
        line = " ".join(_BULLET.sub("", line, count=1).split())
        if len(line) < 3:
            continue
        merged = []
        for piece in re.split(r"(?<=[.!?])\s+", line):
            if merged and (piece[:1].islower() or merged[-1].rstrip(".").rsplit(" ", 1)[-1].lower() in _ABBREV):
                merged[-1] += " " + piece
            else:
                merged.append(piece)
        units.extend(_cut(piece) for piece in merged if len(piece) >= 3)
    return units


# ---- names -------------------------------------------------------------------------------------------------------


def _fold(name):
    return " ".join(name.split()).casefold()


def _base(token):
    for suffix in ("'s", "’s"):
        if token.endswith(suffix):
            token = token[: -len(suffix)]
    return token.strip("'’-")


def _stop(token):
    return _base(token).replace("’", "'").casefold() in STOP


def valid_name(name):
    name = " ".join(str(name).split())
    return name if 1 < len(name) <= NAME_CHARS and _NAME_OK.match(name) and not name.isdigit() else None


def _capitalised(token):
    base = _base(token)
    return len(base) >= 2 and base[0].isupper() and not base.isupper()


def _runs(unit):
    """The runs of capitalised words in a sentence, as lists of (word, starts_the_sentence), at most three words long."""
    tokens = [(m.group(0), m.start(), m.end()) for m in _TOKEN.finditer(unit)]
    runs, current, previous_end = [], [], None
    for index, (word, start, end) in enumerate(tokens):
        joined = previous_end is not None and unit[previous_end:start] in (" ", "\t")
        if _capitalised(word):
            if current and not joined:
                runs.append(current)
                current = []
            current.append((word, index == 0))
        elif current:
            runs.append(current)
            current = []
        previous_end = end
    if current:
        runs.append(current)
    return runs


def _title_like(unit):
    words = _TOKEN.findall(unit)
    capital = sum(1 for w in words if _capitalised(w))
    return len(words) >= 4 and capital >= 4 and capital / len(words) >= 0.8


def ordinary_words(units_by_note):
    """The words that are written in lowercase at least twice, and more often than with a capital in the middle of a sentence: ordinary words, not names. "call" is one (it is in "to call the vet" and never
    "Call" in the middle of a sentence); "ravi" is not if it was typed lowercase once and capitalised once."""
    lower, capital = Counter(), Counter()
    for units in units_by_note:
        for unit in units:
            for index, word in enumerate(_TOKEN.findall(unit)):
                key = _base(word).casefold()
                if word[0].islower():
                    lower[key] += 1
                elif index > 0 and _capitalised(word):
                    capital[key] += 1
    return {word for word, count in lower.items() if count >= 2 and count > capital[word]}


def derived_candidates(units_by_note, ordinary=None):
    """Capitalised names, as {name: set of note indexes}: only those written with a capital somewhere that is not the start of a sentence (a sentence starts with a capital whatever the word is).
    An ordinary word (ordinary_words) is dropped from the front of a sentence ("Call Maya" is Maya); days, months and common starters never count."""
    if ordinary is None:
        ordinary = ordinary_words(units_by_note)
    found, eligible = defaultdict(set), set()
    for note_index, units in enumerate(units_by_note):
        for unit in units:
            if _title_like(unit):
                continue
            for run in _runs(unit):
                words = [word for word, _ in run]
                if run[0][1]:
                    while words and _base(words[0]).casefold() in ordinary:
                        words.pop(0)
                while words and _stop(words[0]):
                    words.pop(0)
                dropped_in_front = len(run) - len(words)
                while words and _stop(words[-1]):
                    words.pop()
                if not words or len(words) > 3:
                    continue
                titled = len(words) > 1 and _base(words[0]).casefold() in _TITLES  # "Dr Mehta" at the start of a sentence is one name
                named = [(words, not run[0][1] or dropped_in_front > 0 or titled)]
                if run[0][1] and not dropped_in_front and len(words) > 1 and not titled:
                    named.append((words[1:], True))  # "Call Maya": the first word may be nothing but the capital that starts the sentence, and what follows it is mid-sentence
                for chosen, away_from_the_start in named:
                    name = valid_name(" ".join(_base(w) for w in chosen))
                    if name:
                        found[name].add(note_index)
                        if away_from_the_start:
                            eligible.add(name)  # written with a capital where only a name would be
    return {name: where for name, where in found.items() if name in eligible}


def recurring(candidates):
    """The names from derived_candidates that recur: in MIN_NOTES or more different notes."""
    return {name: where for name, where in candidates.items() if len(where) >= MIN_NOTES}


def marked_names(notes):
    """The names a person marked in their notes: `[[Name]]` (only the last part of `folder/Name`) and `@Name`."""
    found, refused = {}, 0
    for note in notes:
        text = "\n".join(_lines(note.text))
        for raw in [m.group(1) for m in _WIKI.finditer(text)] + [m.group(1) for m in _AT.finditer(text)]:
            name = valid_name(raw.replace("\\", "/").split("/")[-1])
            if name:
                found.setdefault(_fold(name), name)
            else:
                refused += 1
    return found, refused


def known_people(db_path):
    """The names in Diya's `people` table, without opening the database for writing or making one that is not there."""
    if not db_path or not os.path.isfile(db_path):
        return []
    try:
        conn = sqlite3.connect(Path(db_path).resolve().as_uri() + "?mode=ro", uri=True)
        try:
            return [row[0] for row in conn.execute("SELECT name FROM people ORDER BY id")]
        finally:
            conn.close()
    except sqlite3.Error:
        return []


# ---- the pages ---------------------------------------------------------------------------------------------------


def safe_stem(name):
    """A file name (without .md) for a name: letters, digits, spaces and a few marks, nothing that can be a path, never a name the system reserves. None if nothing is left."""
    stem = " ".join(re.sub(r"[^\w \-'’.&]", "", name).split()).strip(" .")[:NAME_CHARS].strip(" .")
    if not stem:
        return None
    return stem + " (page)" if stem.casefold() in _RESERVED else stem


def _is_generated(path):
    try:
        if os.path.islink(path) or not os.path.isfile(path):
            return False
        with open(path, encoding="utf-8", errors="replace") as handle:
            return handle.readline().startswith(MARKER_PREFIX)
    except OSError:
        return False


def hidden_names(out_dir):
    """The names in the hidden file as the person wrote them, in order."""
    path = os.path.join(out_dir, HIDDEN_FILE)
    if not os.path.isfile(path):
        return []
    with open(path, encoding="utf-8", errors="replace") as handle:
        return [" ".join(line.split()) for line in handle.read().splitlines() if line.strip() and not line.lstrip().startswith("#")]


def load_hidden(out_dir):
    return {_fold(name) for name in hidden_names(out_dir)}


def _write(path, text, dry_run):
    """Write a file only when its content changed; return 'written' or 'unchanged'."""
    data = text.encode("utf-8")
    try:
        with open(path, "rb") as handle:
            if handle.read() == data:
                return "unchanged"
    except OSError:
        pass
    if not dry_run:
        temporary = path + ".tmp"
        with open(temporary, "wb") as handle:
            handle.write(data)
        os.replace(temporary, path)
    return "written"


def _page_text(name, bullets, omitted, links):
    out = [MARKER, "", f"# {name}", "",
           f"*Your own words from your notes, grouped by name. Diya has not accepted any of this as a fact about you. To remove this page: `python diya_knowledge.py hide \"{name}\"`.*", ""]
    out += [f"- {printable(text)} — {source}" for text, source in bullets]
    if omitted:
        out.append(f"- ...and {omitted} more in your notes")
    if links:
        out += ["", "Mentioned with: " + ", ".join(f"[[{link}]]" for link in links)]
    return "\n".join(out) + "\n"


def _index_text(entries, notes):
    out = [MARKER, "", "# Knowledge from your notes", "",
           f"Built from {notes} notes: {len(entries)} pages. Each page is your own sentences, grouped by the name they mention. Diya has not accepted any of it as a fact about you.", ""]
    out += [f"- [[{stem}]] — {sentences} sentence{'s' if sentences != 1 else ''} in {count} note{'s' if count != 1 else ''}" for stem, sentences, count in entries]
    return "\n".join(out) + "\n"


def build(notes_dir, out_dir, known=(), dry_run=False):
    """Read the notes and write the pages. Returns a Report; raises KnowledgeError for a problem the person has to fix."""
    notes_real, out_real = os.path.realpath(notes_dir), os.path.realpath(out_dir)
    if _inside(notes_real, out_real) or _inside(out_real, notes_real):
        raise KnowledgeError(f"the knowledge folder {out_dir!r} and the notes folder {notes_dir!r} must be two separate folders (Diya would read its own pages back as notes)")
    notes, skipped = read_notes(notes_dir, skip=(out_dir,))
    report = Report(notes=len(notes), skipped=skipped)
    units_by_note = [list(dict.fromkeys(units_of(note.text)))[:MAX_UNITS_PER_NOTE] for note in notes]

    marked, refused = marked_names(notes)
    report.refused_names = refused
    hidden = load_hidden(out_dir)
    entities = {}  # folded name -> (display name, how it is matched: "ci" or "cs")
    ordinary = ordinary_words(units_by_note)

    def matched_as(name):
        """"ravi called" is the same Ravi; but "will" is not "Will": a name with an ordinary word in it is matched only as it is written."""
        return "cs" if any(word.casefold() in ordinary for word in re.findall(r"[\w'’\-]+", name)) else "ci"

    for name in list(known) + list(marked.values()):
        valid = valid_name(name)
        if valid and _fold(valid) not in hidden:
            entities.setdefault(_fold(valid), (valid, matched_as(valid)))
    for name in sorted(recurring(derived_candidates(units_by_note, ordinary))):
        if _fold(name) not in hidden:
            entities.setdefault(_fold(name), (name, matched_as(name)))

    def pattern(kind):
        names = sorted((display for display, how in entities.values() if how == kind), key=lambda n: (-len(n), n))
        if not names:
            return None
        return re.compile(r"(?<!\w)(?:" + "|".join(re.escape(n) for n in names) + r")(?!\w)", re.IGNORECASE if kind == "ci" else 0)

    ci, cs = pattern("ci"), pattern("cs")
    mentions = defaultdict(list)  # folded name -> [(note index, text)]
    together = Counter()
    for note_index, units in enumerate(units_by_note):
        for unit in units:
            hit = set()
            for regex in (ci, cs):
                if regex is None:
                    continue
                for match in regex.finditer(unit):
                    hit.add(_fold(match.group(0)))
                    for part in re.findall(r"[\w'’\-]+", match.group(0)):
                        if _fold(_base(part)) in entities:
                            hit.add(_fold(_base(part)))
            hit = {key for key in hit if key in entities}
            for key in hit:
                mentions[key].append((note_index, unit))
            for a in hit:
                for b in hit:
                    if a < b:
                        together[(a, b)] += 1

    ranked = sorted(mentions, key=lambda key: (-len(mentions[key]), key))
    report.over_page_limit = max(0, len(ranked) - MAX_PAGES)
    ranked = ranked[:MAX_PAGES]
    if not dry_run:
        os.makedirs(out_dir, exist_ok=True)
    stems, used, expected, index_entries = {}, set(), {INDEX_STEM + ".md"}, []
    for key in ranked:
        stem = safe_stem(entities[key][0])
        if stem is None:
            report.refused_names += 1
            continue
        candidate, number = stem, 1
        while candidate.casefold() in used:
            number += 1
            candidate = f"{stem} {number}"
        existing = os.path.join(out_dir, candidate + ".md")
        if os.path.exists(existing) and not _is_generated(existing):
            report.collisions.append(candidate + ".md")
            continue
        used.add(candidate.casefold())
        stems[key] = candidate
    for key, stem in stems.items():
        seen, ordered = set(), []
        for note_index, text in sorted(mentions[key], key=lambda item: (-notes[item[0]].mtime, notes[item[0]].path)):
            if (note_index, text) not in seen:
                seen.add((note_index, text))
                ordered.append((text, notes[note_index].path))
        shown = ordered[:MAX_BULLETS]
        links = [stems[other] for other in sorted(
            (k for k in stems if k != key and together.get((min(key, k), max(key, k)), 0)),
            key=lambda k: (-together[(min(key, k), max(key, k))], stems[k].casefold()))][:MAX_WITH]
        outcome = _write(os.path.join(out_dir, stem + ".md"), _page_text(entities[key][0], shown, len(ordered) - len(shown), links), dry_run)
        (report.written if outcome == "written" else report.unchanged).append(stem + ".md")
        expected.add(stem + ".md")
        index_entries.append((stem, len(ordered), len({note for note, _ in mentions[key]})))
    report.pages = len(index_entries)
    index_entries.sort(key=lambda e: (-e[1], e[0].casefold()))
    index_path = os.path.join(out_dir, INDEX_STEM + ".md")
    if os.path.exists(index_path) and not _is_generated(index_path):
        report.collisions.append(INDEX_STEM + ".md")
    else:
        _write(index_path, _index_text(index_entries, len(notes)), dry_run)

    if os.path.isdir(out_dir):
        for name in sorted(os.listdir(out_dir)):
            path = os.path.join(out_dir, name)
            if name.endswith(".md") and name not in expected and _is_generated(path):
                if not dry_run:
                    os.remove(path)
                report.removed.append(name)
    return report


# ---- hiding, listing ---------------------------------------------------------------------------------------------


def hide(out_dir, name):
    """Never make a page for `name`, and remove the one that exists if Diya made it. Returns True if it was not hidden before."""
    clean = valid_name(name)
    if clean is None:
        raise KnowledgeError(f"{printable(name, 80)!r} is not a name Diya makes pages for (letters, digits, spaces and a few marks)")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, HIDDEN_FILE)
    new = _fold(clean) not in load_hidden(out_dir)
    if new:
        header = "" if os.path.isfile(path) else "# Names Diya will not make a page for, one per line. Delete a line (or run `unhide`) to get it back.\n"
        with open(path, "a", encoding="utf-8", newline="\n") as handle:
            handle.write(header + clean + "\n")
    stem = safe_stem(clean)
    page = os.path.join(out_dir, stem + ".md") if stem else None
    if page and _is_generated(page):
        os.remove(page)
    return new


def unhide(out_dir, name):
    """Make a page for `name` again from the next build. Returns True if it was hidden."""
    clean = valid_name(name)
    path = os.path.join(out_dir, HIDDEN_FILE)
    if clean is None or not os.path.isfile(path):
        return False
    with open(path, encoding="utf-8", errors="replace") as handle:
        lines = handle.read().splitlines()
    kept = [line for line in lines if line.lstrip().startswith("#") or _fold(line) != _fold(clean)]
    if len(kept) == len(lines):
        return False
    _write(path, "\n".join(kept) + ("\n" if kept else ""), False)
    return True


def list_pages(out_dir):
    """The names of the pages Diya made, and the names hidden."""
    if not os.path.isdir(out_dir):
        return [], hidden_names(out_dir)
    pages = [name[:-3] for name in sorted(os.listdir(out_dir)) if name.endswith(".md") and name != INDEX_STEM + ".md" and _is_generated(os.path.join(out_dir, name))]
    return pages, hidden_names(out_dir)


def read_page(out_dir, stem):
    """A page Diya made, read back from its own file: {stem, name, sentences: [{text, source}], omitted, links: [stem]}. None if there is no such page, or the file is not one of Diya's (a
    file of the person's own is never read as a page, and `stem` is only ever used as a name inside the knowledge folder)."""
    if not stem or os.path.basename(stem) != stem or stem != stem.strip() or stem.startswith("."):
        return None
    path = os.path.join(out_dir, stem + ".md")
    if stem == INDEX_STEM or not _is_generated(path):
        return None
    with open(path, encoding="utf-8", errors="replace") as handle:
        lines = handle.read().splitlines()
    name, sentences, omitted, links = stem, [], 0, []
    for line in lines[1:]:
        if line.startswith("# ") and name == stem:
            name = line[2:].strip() or stem
            continue
        match = re.match(r"^- (.*) — (.+)$", line)  # the last " — " splits a sentence from the note's path, which may have spaces in it
        if match:
            sentences.append({"text": match.group(1), "source": match.group(2)})
        elif re.match(r"^- \.\.\.and (\d+) more", line):
            omitted = int(re.match(r"^- \.\.\.and (\d+) more", line).group(1))
        elif line.startswith("Mentioned with: "):
            links = re.findall(r"\[\[([^\]]+)\]\]", line)
    return {"stem": stem, "name": name, "sentences": sentences, "omitted": omitted, "links": links}


# ---- the command line --------------------------------------------------------------------------------------------


def _plural(count, word):
    return f"{count} {word}{'' if count == 1 else 's'}"


def main(argv=None, config=None, out=None):
    out = out or sys.stdout
    config = config or diya_config.load_config()
    parser = argparse.ArgumentParser(prog="diya_knowledge.py", description="Pages made from your own notes (docs/KNOWLEDGE_DESIGN.md).")
    commands = parser.add_subparsers(dest="command", required=True)
    build_parser = commands.add_parser("build", help="read the notes and write the pages")
    build_parser.add_argument("--notes", help="the notes folder (default DIYA_NOTES_DIR)")
    build_parser.add_argument("--out", help="the knowledge folder (default DIYA_KNOWLEDGE_DIR)")
    build_parser.add_argument("--dry-run", action="store_true", help="say what would change and change nothing")
    commands.add_parser("list", help="the pages that exist and the names hidden")
    for name in ("hide", "unhide"):
        commands.add_parser(name, help=f"{name} a name").add_argument("name", nargs="+")
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:
        return EXIT_USAGE if exc.code else EXIT_OK
    target = getattr(args, "out", None) or config.knowledge_dir
    try:
        if args.command == "build":
            report = build(args.notes or config.notes_dir, target, known_people(config.db_path), dry_run=args.dry_run)
            verb = "would be" if args.dry_run else "were"
            print(f"Read {_plural(report.notes, 'note')} in {printable(args.notes or config.notes_dir)}.", file=out)
            for line in report.skipped:
                print(f"  left out: {printable(line)}", file=out)
            print(f"{_plural(report.pages, 'page')} in {printable(target)}: {len(report.written)} {verb} written, {len(report.unchanged)} unchanged, {len(report.removed)} {verb} removed.", file=out)
            for name in report.collisions:
                print(f"  skipped {printable(name)}: a file of yours with that name is already there", file=out)
            if report.refused_names:
                print(f"  {_plural(report.refused_names, 'name')} not used (not made of letters, digits, spaces and a few marks)", file=out)
            if report.over_page_limit:
                print(f"  {report.over_page_limit} more names had no page: the limit is {MAX_PAGES}", file=out)
            if not report.pages:
                print("No name recurs in your notes yet (a name needs a capital letter and to be in two notes, or be written [[like this]]).", file=out)
        elif args.command == "list":
            pages, hidden = list_pages(target)
            print(f"{_plural(len(pages), 'page')}: " + (", ".join(printable(p) for p in pages) or "none"), file=out)
            if hidden:
                print("hidden: " + ", ".join(printable(h) for h in hidden), file=out)
        elif args.command == "hide":
            name = " ".join(args.name)
            print(("Hidden: " if hide(target, name) else "Already hidden: ") + printable(name), file=out)
        else:
            name = " ".join(args.name)
            print(("It will come back on the next build: " if unhide(target, name) else "It was not hidden: ") + printable(name), file=out)
    except KnowledgeError as exc:
        print(f"Not done: {printable(str(exc))}", file=out)
        return EXIT_FAILED
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
